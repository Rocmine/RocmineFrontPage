"""Orchestrates a build: pages, stylesheet, script, sitemap, robots."""
import filecmp
import sys
import tempfile
from pathlib import Path

from . import config, pages
from .config import ROOT, SITE, SRC
from .layout import write
from .svg import write_thumbs

PAGES = [
    # (output file, builder, sitemap path or None)
    ("index.html", pages.home, "/"),
    ("work/index.html", pages.work, "/work/"),
    ("work/earthquake-tracker/index.html", pages.quake, "/work/earthquake-tracker/"),
    ("work/datacenter-hci/index.html", pages.datacenter, "/work/datacenter-hci/"),
    ("lab/index.html", pages.lab, "/lab/"),
    ("about/index.html", pages.about, "/about/"),
    ("404.html", pages.notfound, None),
]


def concat(folder, ext):
    banner = f"/* GENERATED by tools/build.py from src/{folder}/*.{ext}. Edit the sources, not this file. */\n"
    return banner + "".join(p.read_text(encoding="utf8") for p in sorted((SRC / folder).glob(f"*.{ext}")))


def build_all():
    write_thumbs()
    for rel, fn, _ in PAGES:
        write(rel, fn())
    write("assets/css/main.css", concat("css", "css"))
    write("assets/js/main.js", concat("js", "js"))
    urls = [u for _, _, u in PAGES if u]
    sm = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "".join(
        f"  <url><loc>{SITE}{u}</loc><lastmod>2026-10-04</lastmod></url>\n" for u in urls) + "</urlset>\n"
    write("sitemap.xml", sm)
    write("robots.txt", f"User-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n")


def main(argv):
    check = "--check" in argv
    if check:
        out = Path(tempfile.mkdtemp(prefix="rocmine-build-"))
        config.OUT = out
    build_all()
    if not check:
        print(f"built {len(config.WRITTEN)} files")
        if "--serve" in argv:
            serve()
        return
    stale = [rel for rel in config.WRITTEN
             if not (ROOT / rel).exists() or not filecmp.cmp(config.OUT / rel, ROOT / rel, shallow=False)]
    if stale:
        print("STALE (run: python tools/build.py):")
        for rel in stale:
            print("  ", rel)
        sys.exit(1)
    print(f"ok: {len(config.WRITTEN)} generated files are up to date")


def serve(port=8080):
    import http.server
    import functools
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ROOT))
    print(f"serving http://localhost:{port}  (Ctrl+C to stop)")
    http.server.ThreadingHTTPServer(("", port), handler).serve_forever()
