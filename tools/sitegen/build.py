def build_all():
    css = concat("css", "css")
    js = concat("js", "js")
    config.VERSION["css"] = short_hash(css)
    config.VERSION["js"] = short_hash(js)
    write_thumbs()
    for rel, fn, _ in PAGES:
        write(rel, fn())
    write("assets/css/main.css", css)
    write("assets/js/main.js", js)
    urls = [u for _, _, u in PAGES if u]
    sm = '<?xml version="1.0" encoding="UTF-8"?>' + chr(10) + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' + chr(10) + "".join(
        f"  <url><loc>{SITE}{u}</loc><lastmod>{LASTMOD}</lastmod></url>" + chr(10) for u in urls) + "</urlset>" + chr(10)
    write("sitemap.xml", sm)
    write("robots.txt", f"User-agent: *{chr(10)}Allow: /{chr(10)}{chr(10)}Sitemap: {SITE}/sitemap.xml{chr(10)}")
    write("site.webmanifest", json.dumps(MANIFEST, ensure_ascii=False, indent=2) + chr(10))
    write(".well-known/security.txt", SECURITY_TXT)
    write("humans.txt", HUMANS_TXT)


def main(argv):
    check = "--check" in argv
    if check:
        out = Path(tempfile.mkdtemp(prefix="rocmine-build-"))
        config.OUT = out
    build_all()
    if not check:
        print(f"built {len(config.WRITTEN)} files")
        if "--serve" in argv:
            serve()
        return
    stale = [rel for rel in config.WRITTEN
             if not (ROOT / rel).exists() or not filecmp.cmp(config.OUT / rel, ROOT / rel, shallow=False)]
    if stale:
        print("STALE (run: python tools/build.py):")
        for rel in stale:
            print("  ", rel)
        sys.exit(1)
    print(f"ok: {len(config.WRITTEN)} generated files are up to date")


def serve(port=8080):
    import http.server
    import functools
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ROOT))
    print(f"serving http://localhost:{port}  (Ctrl+C to stop)")
    http.server.ThreadingHTTPServer(("", port), handler).serve_forever()
