"""Writes src/content/github.json from the public GitHub API (no token needed).

    python tools/fetch_github.py [username]

The result is committed, so the site build never calls the network. Re-run it
whenever you want the "On GitHub" strip on /stack/ refreshed.
"""
import json
import sys
import urllib.request
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "content" / "github.json"


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "rocmine-site-build", "Accept": "application/vnd.github+json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def main(login="Rocmine"):
    user = get(f"https://api.github.com/users/{login}")
    repos = get(f"https://api.github.com/users/{login}/repos?per_page=100&type=owner&sort=pushed")
    own = [r for r in repos if not r["fork"] and not r["archived"]]
    langs = Counter(r["language"] for r in own if r["language"])
    data = {
        "_note": "Generated by tools/fetch_github.py. Do not edit by hand.",
        "fetched": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "login": user["login"],
        "since": int(user["created_at"][:4]),
        "public_repos": user["public_repos"],
        "own_repos": len(own),
        "forks": sum(1 for r in repos if r["fork"]),
        "languages": [{"name": n, "repos": c} for n, c in langs.most_common()],
        "names": sorted(r["name"] for r in repos),   # used by tools/check.py only; never rendered
    }
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf8")
    print(f"wrote {OUT.name}: {data['public_repos']} public repos, {data['own_repos']} own, languages {[l['name'] for l in data['languages']]}")


if __name__ == "__main__":
    main(*sys.argv[1:2])
