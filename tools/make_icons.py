def brand_ids():
    ids = set()
    for r in RULES["rules"]:
        if r["i"] not in GENERIC:
            ids.add(r["i"])
    return sorted(ids)


def fetch(slug):
    dest = MASTERS / f"{slug}.svg"
    if dest.exists():
        return dest.read_text(encoding="utf8")
    try:
        req = urllib.request.Request(RAW.format(slug), headers={"User-Agent": "rocmine-site-build"})
        data = urllib.request.urlopen(req, timeout=30).read().decode("utf8")
    except urllib.error.HTTPError:
        return None
    MASTERS.mkdir(parents=True, exist_ok=True)
    dest.write_text(data, encoding="utf8")
    return data


def main():
    symbols, missing = [], []
    for slug in brand_ids():
        svg = fetch(slug)
        m = svg and re.search(r'<path d="([^"]+)"', svg)
        if not m:
            missing.append(slug)
            continue
        symbols.append(f'<symbol id="{slug}" viewBox="0 0 24 24"><path fill="currentColor" d="{m.group(1)}"/></symbol>')
    for gid, body in GENERIC.items():
        symbols.append(f'<symbol id="{gid}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" '
                       f'stroke-linecap="round" stroke-linejoin="round">{body}</symbol>')
    SPRITE.parent.mkdir(parents=True, exist_ok=True)
    SPRITE.write_text('<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n' + "\n".join(symbols) + "\n</svg>\n", encoding="utf8")
    (SPRITE.parent / "README.md").write_text(
        "# Icons\n\n`sprite.svg` is generated by `tools/make_icons.py`.\n\n"
        "- Brand logos: [Simple Icons](https://github.com/simple-icons/simple-icons), CC0 1.0. "
        "Logos remain trademarks of their owners and are used only to name the technology.\n"
        "- Generic line glyphs: drawn for this site.\n", encoding="utf8")
    print(f"sprite: {len(symbols)} symbols ({len(symbols) - len(GENERIC)} brand, {len(GENERIC)} generic), "
          f"{SPRITE.stat().st_size // 1024} KB")
    if missing:
        print("not in Simple Icons (generic fallback used):", ", ".join(missing))


if __name__ == "__main__":
    main()
